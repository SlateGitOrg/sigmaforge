"""Differential tests: the SQLite backend must select exactly the events the evaluator matches.

Random rules (YAML level) and random events are generated by Hypothesis; each rule is compiled,
rendered to SQL, executed against an in-memory SQLite table holding the events, and the selected
row set is compared with the reference evaluator's verdicts.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from hypothesis import example, given

from sigmaforge.ast import Node, fields
from sigmaforge.backends.sqlite import SQLiteBackend
from sigmaforge.compiler import compile_rule
from sigmaforge.evaluator import Evaluator, evaluate
from sigmaforge.rule import load_rule, rule_from_dict
from sigmaforge.sqlite_runtime import connect, load_events, run_query
from tests.helpers import load_jsonl, subtree_disagreements
from tests.strategies import FIELDS, rule_and_events


def sql_matches(node_rule: Any, evs: list[dict[str, Any]]) -> list[int]:
    query = SQLiteBackend(keyword_columns=FIELDS).convert(node_rule).text
    conn = connect()
    try:
        load_events(conn, evs, extra_columns=FIELDS)
        return run_query(conn, query)
    finally:
        conn.close()


EXAMPLES: list[tuple[dict[str, Any], list[dict[str, Any]]]] = [
    (  # NULL under NOT: a missing field must make "not sel" true
        {"title": "null under not", "detection": {"sel1": {"User": "x"}, "condition": "not sel1"}},
        [{}, {"User": "X"}, {"User": None}],
    ),
    (  # LIKE metacharacters must be escaped
        {
            "title": "like metacharacters",
            "detection": {"sel1": {"Image|contains": ["%", "_", "\\"]}, "condition": "sel1"},
        },
        [{"Image": "a%b"}, {"Image": "ab"}, {"Image": "a_b"}, {"Image": "x\\y"}],
    ),
    (  # only ASCII letters fold case
        {
            "title": "non-ascii case folding",
            "detection": {"sel1": {"User": "\u00e9", "Image": "k"}, "condition": "1 of them"},
        },
        [{"User": "\u00c9"}, {"Image": "\u212a"}, {"Image": "K"}],
    ),
    (  # integers vs their text, and comparisons only on real numbers
        {
            "title": "numbers vs text",
            "detection": {"sel1": {"EventID": 4688, "Port|gt": 5}, "condition": "all of them"},
        },
        [{"EventID": "4688", "Port": 6}, {"EventID": 4688, "Port": "6"}, {"EventID": "04688"}],
    ),
]


@given(rule_and_events())
@example(EXAMPLES[0])
@example(EXAMPLES[1])
@example(EXAMPLES[2])
@example(EXAMPLES[3])
def test_sql_backend_agrees_with_evaluator(
    case: tuple[dict[str, Any], list[dict[str, Any]]],
) -> None:
    doc, evs = case
    compiled = compile_rule(rule_from_dict(doc))
    expected = Evaluator(compiled.node).filter(evs)
    assert sql_matches(compiled, evs) == expected


@given(rule_and_events())
def test_every_subtree_agrees(case: tuple[dict[str, Any], list[dict[str, Any]]]) -> None:
    """Stronger than whole-rule agreement: no node of the tree may disagree on any event."""
    doc, evs = case
    compiled = compile_rule(rule_from_dict(doc))
    assert subtree_disagreements(compiled.node, evs, FIELDS) == []


@given(rule_and_events())
def test_simplifier_preserves_semantics(case: tuple[dict[str, Any], list[dict[str, Any]]]) -> None:
    doc, evs = case
    rule = rule_from_dict(doc)
    raw: Node = compile_rule(rule, optimize=False).node
    simplified: Node = compile_rule(rule).node
    for event in evs:
        assert evaluate(raw, event) == evaluate(simplified, event)


def test_demo_rules_agree_on_fixture_events(root: Path) -> None:
    evs = load_jsonl(root / "examples" / "events" / "windows.jsonl")
    rules = sorted((root / "examples" / "rules").glob("*.yml"))
    assert rules
    for path in rules:
        compiled = compile_rule(load_rule(path))
        columns = sorted({k for e in evs for k in e})
        query = SQLiteBackend(keyword_columns=columns).convert(compiled).text
        conn = connect()
        load_events(conn, evs, extra_columns=fields(compiled.node))
        assert run_query(conn, query) == Evaluator(compiled.node).filter(evs), path.name
